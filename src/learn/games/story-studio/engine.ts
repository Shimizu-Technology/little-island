const narrated = (task: Task): Task => ({ ...task, audio: readingSpeech(task.clue),
  cardAudio: Object.fromEntries([...task.answer, ...task.extras].map(card => [card, readingSpeech(card)])) });
export const bank: Task[][] = [
  scenes.map(([a, b, c]) => narrated({
    prompt: `${b} · ${c}`,
    clue: `Build the picture sentence: ${a} ${b} ${c}.`,
    answer: [a, b, c],
    extras: ["on", "blue"],
    slots: ["Start", "Who?", "Does what?"],
    picture: b,
  })),
  repairs.map(([raw, a, b, c]) => narrated({
    prompt: `Repair: ${raw}`,
    clue: `Repair this sentence: ${a} ${b}${c} A sentence starts with a capital. A question ends with a question mark. A telling sentence ends with a full stop.`,
    answer: [a, b, c],
    extras: [a.toLowerCase(), c === "." ? "?" : "."],
    slots: ["Capital start", "Keep the words", "End mark"],
  })),
  roles.map(([noun, verb, adj]) => ({
    prompt: `Sort, then expand: The ${noun} ${verb}.`,
    clue: "A noun names a thing. A verb tells an action. An adjective describes a noun. Then build the expanded sentence.",
    answer: [noun, verb, adj, "The", adj, noun, verb + "."],
    extras: ["quickly"],
    slots: ["Noun", "Verb", "Adjective", "Sentence start", "Describe it", "Who?", "Action"],
  })),
  stories.map(([a, b, c, idea, picture], i) => ({
    panels: comicPictures[i],
    prompt: "Put the comic in order, then give it a main idea.",
    clue: "Find what happens first. Look for what changes next, then how the problem ends. The main idea covers the whole story.",
    answer: [a, b, c, idea],
    extras: ["Nothing changes in this story."],
    slots: ["Beginning", "Middle", "End", "Main idea"],
    picture,
  })),
  paragraphs.flatMap(([topic, d1, d2, end, bad, good, passage, inference]) => [
    {
      prompt: "Build a paragraph with one clear focus.",
      clue:
        "Start with the topic. Add two supporting details in the order shown by the clue: " +
        d1 +
        " Then " +
        d2 +
        " Finish with a conclusion.",
      answer: [topic, d1, d2, end],
      extras: ["And then a spaceship ate the moon."],
      slots: ["Topic sentence", "Detail 1", "Detail 2", "Conclusion"],
    },
    {
      prompt: `Edit in the present tense: ${bad} Then read: ${passage}`,
      clue: "Use the present tense. Match the verb to its subject. Use the passage as evidence for your inference.",
      answer: [...good.split(" "), inference],
      extras: [...bad.split(" "), "There is no clue in the passage."],
      slots: [...good.split(" ").map((_, i) => `Edit word ${i + 1}`), "Inference from evidence"],
    },
  ]),
];
