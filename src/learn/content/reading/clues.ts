// Picture prompts for Sound Boat. A word is only ever shown as a picture when the drawing IS that word and a
// 7-year-old names it straight away (no "person" for man or a green blob for fig). Every other word is heard,
// and written under its picture spot when sound is off.
export const PICTURE_WORDS: Record<"easy" | "medium" | "hard", readonly string[]> = {
  easy: ["cat", "hat", "hen", "pig", "fox", "box", "dog", "sun", "bus", "cup", "bug", "bed", "log"],
  medium: ["shell", "fish", "crab", "frog", "duck", "rock", "kite", "bike", "cake", "nest"],
  hard: ["sheep", "tree", "bee", "leaf", "seal", "boat", "goat", "moon", "boot", "car", "star", "jar", "fork"],
};
const pictured = new Set(Object.values(PICTURE_WORDS).flat());
/** The drawing for a word, only when it is instantly nameable. */
export function pictureFor(word: string): string | undefined {
  const w = word.toLowerCase();
  return pictured.has(w) ? w : undefined;
}
